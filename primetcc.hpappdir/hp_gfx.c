/*
 * hp_gfx.c -- graphics library for TCC-compiled programs on the HP Prime G1.
 *
 * Self-contained plain C (TCC-compilable on the calculator).  The only
 * firmware dependency is get_lcd (svc 0x1008d), provided by rt_svc.o.
 *
 * Framebuffer layout (verified against the working gbemu port):
 *   get_lcd() -> r0 = P;  Q = *(u32*)P;  w = *(u16*)(Q+2);
 *   h = *(u16*)(Q+4);  fb = *(u32*)(Q+16);  pixels are u32 0x00RRGGBB.
 */
#include "hp_gfx.h"

/* memory (provided by hp_rt.c, which user programs link) */
typedef unsigned int size_t;
void *malloc(size_t n);
void  free(void *p);

/* ---- firmware get_lcd (rt_svc.o) ---- */
unsigned hp_svc_getlcd(unsigned dummy);

/* ---- state ---- */
static unsigned int *g_fb;    /* LCD framebuffer base (from get_lcd) */
static int g_w;               /* LCD width */
static int g_h;               /* LCD height */
static int g_ok;              /* init done */
/* current drawing target: the screen fb by default, or a selected grob */
static unsigned int *g_tgt;
static int g_tw;
static int g_th;

/* embedded 5x8 font (defined at the bottom of this file) */
static const unsigned char hp_font5x8[640];

int hp_gfx_init(void)
{
    unsigned p, q;
    if (g_ok)
        return 1;
    p = hp_svc_getlcd(0);
    if (!p)
        return 0;
    q = *(unsigned int *)p;          /* LCD info struct */
    if (!q)
        return 0;
    g_w = *(unsigned short *)(q + 2);
    g_h = *(unsigned short *)(q + 4);
    g_fb = (unsigned int *)(*(unsigned int *)(q + 16));
    if (!g_fb || g_w <= 0 || g_h <= 0)
        return 0;
    g_ok = 1;
    g_tgt = g_fb;
    g_tw = g_w;
    g_th = g_h;
    return 1;
}

int hp_gfx_w(void) { return g_w; }
int hp_gfx_h(void) { return g_h; }

void hp_pixel(int x, int y, hp_color c)
{
    if (!g_ok)
        return;
    if (x < 0 || y < 0 || x >= g_w || y >= g_h)
        return;
    g_tgt[y * g_tw + x] = (unsigned int)c;
}

hp_color hp_get_pixel(int x, int y)
{
    if (!g_ok)
        return 0;
    if (x < 0 || y < 0 || x >= g_w || y >= g_h)
        return 0;
    return (hp_color)g_tgt[y * g_tw + x];
}

void hp_clear(hp_color c)
{
    int n, i;
    unsigned int *p;
    if (!g_ok)
        return;
    n = g_tw * g_th;
    p = g_tgt;
    for (i = 0; i < n; i++)
        p[i] = (unsigned int)c;
}

void hp_hline(int x, int y, int w, hp_color c)
{
    int i;
    if (!g_ok)
        return;
    if (y < 0 || y >= g_th)
        return;
    if (x < 0) { w += x; x = 0; }
    if (x + w > g_tw) w = g_tw - x;
    for (i = 0; i < w; i++)
        g_tgt[y * g_tw + x + i] = (unsigned int)c;
}

void hp_vline(int x, int y, int h, hp_color c)
{
    int i;
    if (!g_ok)
        return;
    if (x < 0 || x >= g_tw)
        return;
    if (y < 0) { h += y; y = 0; }
    if (y + h > g_th) h = g_th - y;
    for (i = 0; i < h; i++)
        g_tgt[(y + i) * g_tw + x] = (unsigned int)c;
}

void hp_fill_rect(int x, int y, int w, int h, hp_color c)
{
    int i;
    if (!g_ok)
        return;
    if (w <= 0 || h <= 0)
        return;
    for (i = 0; i < h; i++)
        hp_hline(x, y + i, w, c);
}

void hp_rect(int x, int y, int w, int h, hp_color c)
{
    if (!g_ok)
        return;
    if (w <= 0 || h <= 0)
        return;
    hp_hline(x, y, w, c);
    hp_hline(x, y + h - 1, w, c);
    hp_vline(x, y, h, c);
    hp_vline(x + w - 1, y, h, c);
}

/* Bresenham line */
void hp_line(int x0, int y0, int x1, int y1, hp_color c)
{
    int dx, dy, sx, sy, err, e2;
    if (!g_ok)
        return;
    dx = x1 > x0 ? x1 - x0 : x0 - x1;
    dy = y1 > y0 ? y1 - y0 : y0 - y1;
    sx = x0 < x1 ? 1 : -1;
    sy = y0 < y1 ? 1 : -1;
    err = dx - dy;
    for (;;) {
        hp_pixel(x0, y0, c);
        if (x0 == x1 && y0 == y1)
            break;
        e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx)  { err += dx; y0 += sy; }
    }
}

/* midpoint circle (outline) */
void hp_circle(int cx, int cy, int r, hp_color c)
{
    int x = r, y = 0, err = 1 - r;
    if (!g_ok)
        return;
    while (x >= y) {
        hp_pixel(cx + x, cy + y, c);
        hp_pixel(cx - x, cy + y, c);
        hp_pixel(cx + x, cy - y, c);
        hp_pixel(cx - x, cy - y, c);
        hp_pixel(cx + y, cy + x, c);
        hp_pixel(cx - y, cy + x, c);
        hp_pixel(cx + y, cy - x, c);
        hp_pixel(cx - y, cy - x, c);
        y++;
        if (err < 0)
            err += 2 * y + 1;
        else {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}

int hp_text_w(const char *s)
{
    int n = 0;
    if (!s)
        return 0;
    /* advance per char is 6 px (5 glyph + 1 gap); the text occupies
     * [x, x + n), so the next element starts at x + n (no overlap) */
    while (*s) { n += 6; s++; }
    return n;
}

void hp_text_bg(int x, int y, const char *s, hp_color fg, hp_color bg)
{
    int w;
    if (!g_ok || !s)
        return;
    w = hp_text_w(s);
    if (w > 0)
        hp_fill_rect(x, y, w, 8, bg);
    hp_text(x, y, s, fg);
}

void hp_text(int x, int y, const char *s, hp_color c)
{
    unsigned char ch;
    int i, j;
    if (!g_ok || !s)
        return;
    while (*s) {
        ch = (unsigned char)*s++;
        if (ch >= 0x20 && ch < 0x80) {
            /* 5x8 font, 128 glyphs indexed by raw char code */
            const unsigned char *g = hp_font5x8 + ch * 5;
            for (i = 0; i < 5; i++) {
                unsigned char col = g[i];
                if (!col)
                    continue;
                for (j = 0; j < 8; j++) {
                    if (col & (1u << j))
                        hp_pixel(x + i, y + j, c);
                }
            }
        }
        x += 6;
    }
}

/* ---- filled circle (scanline) ---- */
void hp_fill_circle(int cx, int cy, int r, hp_color c)
{
    int y, dy, dx;
    if (!g_ok)
        return;
    for (y = -r; y <= r; y++) {
        dy = y * y;
        dx = 0;
        while (dx * dx + dy <= r * r)
            dx++;
        dx--;
        if (dx < 0)
            continue;
        hp_hline(cx - dx, cy + y, 2 * dx + 1, c);
    }
}

/* ---- GROB layer buffers ---- */
hp_grob *hp_grob_new(int w, int h)
{
    hp_grob *g;
    unsigned *px;
    int n;
    if (w <= 0 || h <= 0)
        return 0;
    n = w * h;
    g = (hp_grob *)malloc(sizeof(hp_grob) + (size_t)n * 4);
    if (!g)
        return 0;
    px = (unsigned *)((char *)g + sizeof(hp_grob));
    g->w = w;
    g->h = h;
    g->px = px;
    for (n--; n >= 0; n--)
        px[n] = 0;
    return g;
}

void hp_grob_free(hp_grob *g)
{
    if (g)
        free(g);
}

void hp_grob_select(hp_grob *g)
{
    if (!g_ok)
        return;
    if (g) {
        g_tgt = g->px;
        g_tw = g->w;
        g_th = g->h;
    } else {
        g_tgt = g_fb;
        g_tw = g_w;
        g_th = g_h;
    }
}

void hp_grob_blit(hp_grob *g, int x, int y)
{
    int sy, n, sx0, sx1;
    unsigned int *dst;
    unsigned int *src;
    if (!g_ok || !g)
        return;
    if (y >= g_h || y + g->h <= 0 || x >= g_w || x + g->w <= 0)
        return;
    if (y < 0) {
        sy = -y;
        n = g->h - sy;
        y = 0;
    } else {
        sy = 0;
        n = g->h;
        if (y + n > g_h)
            n = g_h - y;
    }
    sx0 = x < 0 ? -x : 0;
    sx1 = g->w;
    if (x + sx1 > g_w)
        sx1 = g_w - x;
    if (sx1 <= sx0)
        return;
    dst = g_fb + (unsigned)y * g_w;
    src = g->px + (unsigned)sy * g->w;
    while (n-- > 0) {
        int i;
        for (i = sx0; i < sx1; i++)
            dst[x + i] = src[i];
        dst += g_w;
        src += g->w;
    }
}

